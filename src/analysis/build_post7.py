"""Render reports/post7.html from reports/post7/post7.md.

This used to be a second, hand-written copy of the chapter's prose, sitting
beside the copy in export_post7.py. Day 7 was then rewritten in the exporter
only, and the two silently diverged into different articles — same slug, same
data, different headline, different sections, different conclusions. The file
you opened in a browser was three drafts behind the one being published.

So this no longer holds any prose. The markdown the exporter writes is the
single source of truth, and this renders it. Run order is therefore
export_post7 then build_post7; run.py does that already.

The markdown is generated by us, not written by hand, so the syntax surface is
small and known: headings, paragraphs, bold, italic, links, images, a rule, and
the ledger lines. That is why a 60-line converter is enough and a markdown
dependency is not warranted — but it also means this will not survive someone
hand-adding a table or a list to the markdown, and it says so loudly rather
than dropping it silently.
"""
import html as _html
import re
import shutil

from analysis.report_css import CSS, HEAD
from config import ROOT

MD = ROOT / "reports" / "post7" / "post7.md"
OUT = ROOT / "reports" / "post7.html"
ARCHIVE = ROOT / "reports" / "post7" / "post7-archive.html"

# Markdown the exporter never emits. If one shows up, the chapter grew a
# construct this renderer cannot carry, and a silent drop is how the two copies
# diverged in the first place.
UNSUPPORTED = {"table row": re.compile(r"^\|"),
               "list item": re.compile(r"^\s*([-*+]|\d+\.)\s+"),
               "blockquote": re.compile(r"^>"),
               "code fence": re.compile(r"^```")}


def inline(s):
    """Escape, then re-introduce the inline markup we generate."""
    s = _html.escape(s, quote=False)
    s = re.sub(r"!\[([^\]]*)\]\(([^)]+)\)", r"", s)          # images handled by block
    s = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r'<a href="\2">\1</a>', s)
    s = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", s)
    s = re.sub(r"(?<!\*)\*([^*]+)\*(?!\*)", r"<em>\1</em>", s)
    return s


def main():
    text = MD.read_text()
    for line in text.splitlines():
        for name, pat in UNSUPPORTED.items():
            if pat.match(line):
                raise SystemExit(
                    f"build_post7: post7.md contains a {name} this renderer does "
                    f"not support:\n  {line[:70]}\nAdd it here rather than "
                    f"letting the HTML and the markdown drift apart again.")

    blocks = [b.strip() for b in re.split(r"\n\s*\n", text) if b.strip()]
    title, out, ledger, in_limits = None, [], [], False

    for b in blocks:
        flat = " ".join(b.split())

        if b.startswith("# "):
            title = b[2:].strip()
            out.append(f"<h1>{inline(title)}</h1>")
        elif b.startswith("## "):
            head = b[3:].strip()
            # The Limits section is the report's caveat box, not a chapter.
            if head.lower() == "limits":
                in_limits = True
                out.append('<div class="caveat">\n<h3>Limits</h3>')
            else:
                out.append(f"<h2>{inline(head)}</h2>")
        elif b == "---":
            continue
        elif b.startswith("![") and b.endswith(")"):
            m = re.match(r"!\[(.*)\]\((.+)\)$", flat, re.S)
            alt, src = m.group(1), m.group(2)
            # The ledger PNG duplicates the .ledger block rendered from the same
            # lines of markdown; the report shows the live text version.
            if "key-figures" in src:
                continue
            out.append(f'<figure><img src="post7/{src}" alt="{_html.escape(alt, quote=True)}">'
                       f"<figcaption>{inline(alt)}</figcaption></figure>")
        elif flat.startswith("*Sources:"):
            body = flat[1:-1] if flat.endswith("*") else flat[1:]
            out.append(f"<footer>\n{inline(body)}\n</footer>")
        elif flat.startswith("*") and flat.endswith("*") and title and len(out) == 1:
            out.append(f'<p class="sub">{inline(flat[1:-1])}</p>')
        elif b.startswith("**") and "\n**" in b:
            # The headline ledger: one "**value** label" per line.
            for line in b.splitlines():
                m = re.match(r"\*\*(.+?)\*\*\s*(?:—\s*)?(.*)", line.strip())
                if m:
                    ledger.append(f"  <div><b>{inline(m.group(1))}</b>"
                                  f"<span>{inline(m.group(2).rstrip('.'))}</span></div>")
            out.append('<div class="ledger">\n' + "\n".join(ledger) + "\n</div>")
        else:
            out.append(f"<p>{inline(flat)}</p>")

    if in_limits:
        out.insert(len(out) - 1, "</div>") if out[-1].startswith("<footer") else out.append("</div>")

    body = "\n\n".join(out)
    page = f"{HEAD}<title>{_html.escape(title)}</title>\n<style>{CSS}</style>\n<main>\n{body}\n</main>"
    OUT.write_text(page)
    shutil.copy(OUT, ARCHIVE)
    print(f"wrote {OUT} ({len(page)//1000} KB) and {ARCHIVE.name}")
    print(f"  title: {title}")
    print(f"  {body.count('<h2>')} sections, {body.count('<figure>')} figures, "
          f"{body.count('<a href')} links")


if __name__ == "__main__":
    main()
